//! Every operating-system difference sits here, behind one contract per capability
//! ([ADR-0017](../../../docs/adr/0017-linux-and-container-hosting.md) decision 6,
//! [Linux host design](../../../docs/design/linux-host.md) section 1).
//!
//! Each module exports one non-conditional constructor. It returns the build target's
//! implementation, or the refusing adapter, which reports [`Refused::Unsupported`] and
//! never falls back to another system's behaviour. Platform conditionals stay inside this
//! crate. Consumers keep their policy (which program, which label prefix) and pass it as
//! data. The crate depends on no workspace crate and, because every executable links
//! it, on nothing but the C library (`tests/libc_only.rs`): a capability that only the
//! host consumes and that needs an Apple framework lives in `org-platform-host`. One
//! system library beyond the C library is linked on macOS, `libsandbox`, for the web
//! process's confinement; all four executables linked it before this crate existed,
//! through `org-socket`.
//!
//! macOS adapters exist for every capability. Linux adapters arrive with Track X, one
//! capability at a time (`process`, `socket`, `fs` and `dirs` have theirs); until then
//! the others refuse on Linux as on every other Unix target. No other crate may gain a `cfg` on
//! `target_os`, `target_vendor`, `target_env` or `target_family`:
//! `tests/platform_conditionals.rs` fails on one beyond the shrinking list in
//! `.github/platform-conditionals.allow` (LNX-5).
//!
//! # How a capability is laid out
//!
//! Each capability is one module, `src/<capability>/mod.rs`, with its adapters beside it:
//!
//! - `mod.rs` is the contract: the public types and functions, their documentation, and
//!   the code that is the same on every system. Its public functions are not
//!   conditional; they call `native::…`.
//! - `macos.rs` and `linux.rs` are the adapters for macOS and for GNU/Linux (glibc).
//!   They define the same `pub(super)` items.
//! - `refused.rs` is the adapter for every other Unix target, including Linux with
//!   another C library. Every item in it returns [`Refused`] (or an `io::Error` made
//!   from one). It is compiled and tested on every target, so it cannot rot.
//! - `shared.rs`, where needed, is code only the two real adapters use. It is not
//!   compiled for a refusing target.
//! - `tests.rs` holds the tests of the contract that run on every target, and
//!   `adapter_tests.rs` those that need a real adapter.
//!
//! The only platform predicates are the module declarations at the top of `mod.rs`
//! (`process/mod.rs` is the pattern to copy). They are written out, not generated by a
//! macro, because `cargo fmt` formats only the modules it can see declared. An adapter
//! file is already compiled for one system and needs no predicate. A capability that
//! has only its macOS adapter so far selects between that and `refused` until its Linux
//! adapter is written.

