const INSTANCE: &str = "0190a5d2-7c3e-7a01-8b2c-3d4e5f607182";
const OWNER: &str = "01ARZ3NDEKTSV4RRFFQ69G5FAV";
const OP: &str = "01ARZ3NDEKTSV4RRFFQ69G5FAW";
fn prepared() -> PreparedV1 {
    let id = |n| format!("01900000-0000-7000-8000-{n:012x}");
    PreparedV1 {
        plan: PlanV1 {
            version: 1,
            name: "Example".into(),
            slug: "example".into(),
            repository_remote_url: "https://example.test/org.git".into(),
            state_branch: "org/state".into(),
            home_team_name: "Core".into(),
        },
        organization_id: id(1),
        office_id: id(2),
        repository_id: id(3),
        home_team_id: id(4),
        hr_employee_id: id(5),
    }
}
struct Owner;
impl OwnerAuthority for Owner {
    fn verify_live(&self, _: &AcceptanceIdentity) -> Result<OwnerAccount, OfficeError> {
        Ok(OwnerAccount {
            account_id: "account".into(),
            member_id: OWNER.into(),
        })
    }
}
fn yaml_value(bytes: &[u8]) -> Value {
    let source = format!("---\n{}\n---\n", std::str::from_utf8(bytes).unwrap());
    Value::Object(org_docs::parse(&source).unwrap().front_matter.unwrap())
}
#[test]
fn canonical_bootstrap_is_one_zero_event_commit_and_reopen_never_resets_directory() {
    let dir = tempfile::tempdir().unwrap();
    let canonical = dir.path().canonicalize().unwrap();
    let root = canonical.as_path();
    let public = root.join("state");
    std::fs::create_dir(&public).unwrap();
    let p = prepared();
    let binding = Binding {
        operation_id: OP.into(),
        owner_member_id: OWNER.into(),
        public_root: public.clone(),
        bootstrap: Some(p.clone()),
    };
    let new = NewOffice {
        office_id: p.office_id.clone(),
        org_id: p.organization_id.clone(),
        org_name: p.plan.name.clone(),
        office_name: "London HQ".into(),
        role: OfficeRole::Hq,
    };
    let folder = root.join(&p.office_id);
    let key = Key::from_bytes([63; 32]);
    let office =
        Office::provision_hq_for_instance(&folder, &new, key.clone(), INSTANCE, &binding, |_| {
            LocalRecord::new(
                p.organization_id.clone(),
                OP.into(),
                [4; 65],
                vec![7; 140],
                vec![1; 138],
            )
        })
        .unwrap();
    let config = AcceptanceConfig {
        identity: AcceptanceIdentity {
            instance_id: INSTANCE.into(),
            organization_id: p.organization_id.clone(),
            office_id: p.office_id.clone(),
            machine_id: "machine".into(),
            writer_epoch: 1,
            journal_incarnation: "bootstrap-journal".into(),
        },
        public_root: public.clone(),
        protected_root: root.join("protected"),
        authority: None,
    };
    office.install_selected_acceptance(config.clone()).unwrap();
    office.bind_selected_owner(Arc::new(Owner)).unwrap();
    office.finish_selected_bootstrap(Arc::new(Owner)).unwrap();
    let office_path = public.join(format!("offices/{}.yaml", p.office_id));
    let office_bytes = std::fs::read(&office_path).unwrap();
    let marker: Value =
        serde_json::from_slice(&std::fs::read(folder.join("office.json")).unwrap()).unwrap();
    assert_eq!(marker["office_name"], new.office_name);
    assert_eq!(yaml_value(&office_bytes)["name"], marker["office_name"]);
    let files = materialize(&p, &office.info().office_name, &office.info().created_at)
        .unwrap()
        .1;
    for (path, bytes) in files {
        assert_eq!(std::fs::read(public.join(path)).unwrap(), bytes);
    }
    assert!(!public
        .join(format!("teams/{}/people", p.home_team_id))
        .exists());
    assert!(!public
        .join(format!(
            "teams/{}/agents/{}/execution.md",
            p.home_team_id, p.hr_employee_id
        ))
        .exists());
    let read = |office: &Office| {
        office.local_store().selected_read(|db,_| {
        db.query_row("SELECT ordinal,origin_high_water,(SELECT count(*) FROM selected_directory),(SELECT count(*) FROM selected_receipts) FROM selected_journal_cursor",[],|r|Ok((r.get::<_,i64>(0)?,r.get::<_,i64>(1)?,r.get::<_,i64>(2)?,r.get::<_,i64>(3)?))).map_err(storage)
    }).unwrap()
    };
    let before = read(&office);
    assert_eq!(before, (2, 0, 1, 0));
    // Independent owning-06 assertions, not expected output generated by the
    // production materializer. No published team may have a null reference.
    let team_path = format!("teams/{}/team.yaml", p.home_team_id);
    let counter_path = format!(
        "identity/counters/organization/{}/team.yaml",
        p.organization_id
    );
    let allocation_path = format!(
        "identity/allocations/organization/{}/team/1.yaml",
        p.organization_id
    );
    let team = yaml_value(&std::fs::read(public.join(&team_path)).unwrap());
    assert_eq!(team["number"], 1);
    let counter = yaml_value(&std::fs::read(public.join(&counter_path)).unwrap());
    assert_eq!(
        counter,
        json!({"scope_kind":"organization","scope_id":p.organization_id,"entity_kind":"team","last_number":1})
    );
    let allocation_bytes = std::fs::read(public.join(&allocation_path)).unwrap();
    let allocation = yaml_value(&allocation_bytes);
    assert_eq!(
        allocation,
        json!({"scope_kind":"organization","scope_id":p.organization_id,"entity_kind":"team","number":1,"entity_id":p.home_team_id,"allocated_at":office.info().created_at})
    );
    office.finish_selected_bootstrap(Arc::new(Owner)).unwrap();
    assert_eq!(read(&office), before);
    assert_eq!(std::fs::read(&office_path).unwrap(), office_bytes);
    // Construct a later acknowledged directory/numbering transaction. This is
    // a fixture for existing later state, not a claim that team-creation ships.
    let later_team = "01900000-0000-7000-8000-000000000006".to_owned();
    let mut later: Value = office
        .local_store()
        .selected_read(|db, _| {
            let source: String = db
                .query_row(
                    "SELECT data FROM selected_directory WHERE generation=1",
                    [],
                    |r| r.get(0),
                )
                .map_err(storage)?;
            serde_json::from_str(&source).map_err(storage)
        })
        .unwrap();
    let mut second = later["teams"][&p.home_team_id].clone();
    second["id"] = json!(later_team);
    second["name"] = json!("Later team");
    second["number"] = json!(2);
    later["teams"][&later_team] = second.clone();
    later["source_position"]["seq"] = json!(1);
    let later_source = serde_json::to_vec(&later).unwrap();
    let parsed = codec::parse(&later_source).unwrap();
    let later_source = String::from_utf8(later_source).unwrap();
    let counter2=serde_json::to_vec(&json!({"scope_kind":"organization","scope_id":p.organization_id,"entity_kind":"team","last_number":2})).unwrap();
    let allocation2=serde_json::to_vec(&json!({"scope_kind":"organization","scope_id":p.organization_id,"entity_kind":"team","number":2,"entity_id":later_team,"allocated_at":office.info().created_at})).unwrap();
    let allocation2_path = format!(
        "identity/allocations/organization/{}/team/2.yaml",
        p.organization_id
    );
    let counter_file = counter_path.clone();
    let allocation_file = allocation2_path.clone();
    let second_source = serde_json::to_vec(&second).unwrap();
    let second_path = format!("teams/{later_team}/team.yaml");
    office
        .local_store()
        .selected_transaction(move |db, id| {
            Facts::validate(&parsed, &id.organization_id)?;
            db.execute(
                "INSERT INTO selected_directory VALUES(?1,2,?2,?3)",
                params![
                    id.organization_id,
                    later_source,
                    codec::sha256(later_source.as_bytes())
                ],
            )
            .map_err(storage)?;
            db.execute(
                "UPDATE selected_directory_head SET generation=2 WHERE organization_id=?1",
                [&id.organization_id],
            )
            .map_err(storage)?;
            db.execute(
                "UPDATE selected_artifacts SET content=?2 WHERE namespace='public' AND path=?1",
                params![counter_file, counter2],
            )
            .map_err(storage)?;
            for (path, content, immutable) in [
                (allocation_file, allocation2, true),
                (second_path, second_source, false),
            ] {
                db.execute(
                    "INSERT INTO selected_artifacts VALUES('public',?1,?2,?3)",
                    params![path, content, immutable],
                )
                .map_err(storage)?;
            }
            Ok(())
        })
        .unwrap();
    let advanced = read(&office);
    assert_eq!(advanced, (3, 0, 2, 0));
    let counter_bytes = std::fs::read(public.join(&counter_path)).unwrap();
    let allocation2_bytes = std::fs::read(public.join(&allocation2_path)).unwrap();
    assert_eq!(yaml_value(&counter_bytes)["last_number"], 2);
    // The canonical allocation identity is occupied permanently; a later
    // transaction cannot reuse TEAM-1 by inserting another entity at it.
    let occupied = allocation_path.clone();
    assert!(office
        .local_store()
        .selected_transaction(move |db, _| {
            db.execute(
                "INSERT INTO selected_artifacts VALUES('public',?1,?2,1)",
                params![occupied, b"replacement".as_slice()],
            )
            .map_err(storage)?;
            Ok(())
        })
        .is_err());
    assert_eq!(read(&office), advanced);
    office.finish_selected_bootstrap(Arc::new(Owner)).unwrap();
    assert_eq!(read(&office), advanced);
    drop(office);
    let reopened = Office::open_for_instance(&folder, key, INSTANCE).unwrap();
    reopened.install_selected_acceptance(config).unwrap();
    reopened.bind_selected_owner(Arc::new(Owner)).unwrap();
    reopened.finish_selected_bootstrap(Arc::new(Owner)).unwrap();
    assert_eq!(read(&reopened), advanced);
    assert_eq!(reopened.info().office_name, new.office_name);
    assert_eq!(std::fs::read(&office_path).unwrap(), office_bytes);
    assert_eq!(
        std::fs::read(public.join(&counter_path)).unwrap(),
        counter_bytes
    );
    assert_eq!(
        std::fs::read(public.join(&allocation_path)).unwrap(),
        allocation_bytes
    );
    assert_eq!(
        std::fs::read(public.join(&allocation2_path)).unwrap(),
        allocation2_bytes
    );
    assert_eq!(
        yaml_value(&std::fs::read(public.join(&team_path)).unwrap())["number"],
        1
    );
    let profile = std::fs::read_to_string(public.join(format!(
        "teams/{}/agents/{}/profile.md",
        p.home_team_id, p.hr_employee_id
    )))
    .unwrap();
    let doc = org_docs::SourceDoc::parse(&profile).unwrap();
    assert_eq!(doc.front_matter()["home_team_id"], p.home_team_id);
    assert_eq!(doc.front_matter()["is_owner"], false);
}

#[test]
fn selected_bootstrap_open_and_admission_reject_lost_or_incoherent_prepared_state() {
    for damage in ["missing", "null", "organization", "private-owner"] {
        let dir = tempfile::tempdir().unwrap();
        let public = dir.path().canonicalize().unwrap().join("state");
        std::fs::create_dir(&public).unwrap();
        let p = prepared();
        let bound = Binding {
            operation_id: OP.into(),
            owner_member_id: OWNER.into(),
            public_root: public.clone(),
            bootstrap: Some(p.clone()),
        };
        let new = NewOffice {
            office_id: p.office_id.clone(),
            org_id: p.organization_id.clone(),
            org_name: p.plan.name.clone(),
            office_name: "HQ".into(),
            role: OfficeRole::Hq,
        };
        let folder = dir.path().join(&p.office_id);
        let key = Key::from_bytes([63; 32]);
        let org = p.organization_id.clone();
        let office = Office::provision_hq_for_instance(
            &folder,
            &new,
            key.clone(),
            INSTANCE,
            &bound,
            move |_| LocalRecord::new(org, OP.into(), [4; 65], vec![7; 140], vec![1; 138]),
        )
        .unwrap();
        let path = folder.join("hq-creation.v1.json");
        match damage {
            "missing" => std::fs::remove_file(&path).unwrap(),
            "private-owner" => office
                .local_store()
                .write(|db| {
                    db.execute(
                        "UPDATE meta SET value='different-member' WHERE key='hq_creation_owner'",
                        [],
                    )
                    .map_err(storage)?;
                    Ok(((), None))
                })
                .unwrap(),
            _ => {
                let mut intent: Value =
                    serde_json::from_slice(&std::fs::read(&path).unwrap()).unwrap();
                if damage == "null" {
                    intent["bootstrap"] = Value::Null;
                } else {
                    intent["bootstrap"]["organization_id"] =
                        json!("01900000-0000-7000-8000-000000000009");
                }
                std::fs::write(&path, serde_json::to_vec(&intent).unwrap()).unwrap();
            }
        }
        let config = AcceptanceConfig {
            identity: AcceptanceIdentity {
                instance_id: INSTANCE.into(),
                organization_id: p.organization_id,
                office_id: p.office_id,
                machine_id: "machine".into(),
                writer_epoch: 1,
                journal_incarnation: "journal".into(),
            },
            public_root: public.clone(),
            protected_root: dir.path().canonicalize().unwrap().join("protected"),
            authority: None,
        };
        assert!(
            office
                .validate_hq_creation_admission(&config, INSTANCE)
                .is_err(),
            "{damage}"
        );
        assert!(
            office.install_selected_acceptance(config.clone()).is_err(),
            "{damage}"
        );
        assert!(
            office.finish_selected_bootstrap(Arc::new(Owner)).is_err(),
            "{damage}"
        );
        assert!(!config.protected_root.exists());
        assert_eq!(
            std::fs::read(public.join("security/ca-escrow.v1.bin")).unwrap(),
            vec![7; 140]
        );
        drop(office);
        assert!(
            Office::open_for_instance(folder, key, INSTANCE).is_err(),
            "{damage}"
        );
    }
}
