//! TypeScript generation (ts-rs). The committed output lives in `app/src/lib/api/generated/`;
//! `cargo run -p org-proto --example export-ts` rewrites it, and the `generated_ts` test fails
//! when it is stale.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use ts_rs::{Config, ExportError, TS};

use crate::error::ApiError;
use crate::event::OrgEvent;
use crate::model::KnownTaskStatus;
use crate::rpc::{MethodName, OrgMethods};
use crate::{API_VERSION, EVENT_NOTIFICATION};

/// The barrel file that re-exports every generated type, plus the contract's constants.
pub const INDEX_FILE: &str = "index.ts";

/// Writes the TypeScript for the whole contract into `dir`: one `<Type>.ts` per type (ts-rs)
/// and [`INDEX_FILE`]. Returns the names of the files written, sorted.
///
/// `dir` must be missing or empty, and each path may be exported to at most once per process:
/// ts-rs remembers, per process, which files it has written and merges into them instead of
/// rewriting (even after the directory is deleted). Export into a fresh directory each time.
pub fn export_typescript(dir: &Path) -> Result<Vec<String>, ExportError> {
    if dir.exists() && fs::read_dir(dir)?.next().is_some() {
        return Err(ExportError::Io(std::io::Error::other(format!(
            "{} is not empty",
            dir.display()
        ))));
    }
    fs::create_dir_all(dir)?;

    // serde_json writes u64 as a JSON number, so it is a `number` in TypeScript, not `bigint`.
    let cfg = Config::new().with_out_dir(dir).with_large_int("number");

    // `OrgMethods` reaches every params and result type; the rest are the types the API sends
    // outside a method result (events, errors) or that the UI uses on its own.
    OrgMethods::export_all(&cfg)?;
    OrgEvent::export_all(&cfg)?;
    ApiError::export_all(&cfg)?;
    MethodName::export_all(&cfg)?;
    KnownTaskStatus::export_all(&cfg)?;

    let mut types: Vec<String> = fs::read_dir(dir)?
        .map(|entry| entry.map(|e| e.file_name().to_string_lossy().into_owned()))
        .collect::<Result<_, _>>()?;
    types.sort();

    let mut index = String::new();
    writeln!(
        index,
        "// Generated from crates/org-proto by `cargo run -p org-proto --example export-ts`. Do not edit this file manually.\n"
    )?;
    writeln!(
        index,
        "/** The org API version this contract describes (`hello().api_version`). */"
    )?;
    writeln!(
        index,
        "export const API_VERSION = {API_VERSION} as const;\n"
    )?;
    writeln!(
        index,
        "/** JSON-RPC notification method that carries an `OrgEvent` after `subscribe`. */"
    )?;
    writeln!(
        index,
        "export const EVENT_NOTIFICATION = {EVENT_NOTIFICATION:?} as const;\n"
    )?;
    for file in &types {
        let name = file.strip_suffix(".ts").unwrap_or(file);
        writeln!(index, "export type {{ {name} }} from \"./{name}\";")?;
    }
    fs::write(dir.join(INDEX_FILE), index)?;

    types.push(INDEX_FILE.to_owned());
    types.sort();
    Ok(types)
}
